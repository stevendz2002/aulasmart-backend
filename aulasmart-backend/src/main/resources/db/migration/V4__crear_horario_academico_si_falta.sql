-- Creación diferida de `horario_academico`. La tabla está definida en V1,
-- pero las bases existentes fueron baselined en V1 (baseline-on-migrate)
-- antes de que la tabla se añadiera al esquema inicial: para ellas V1 nunca
-- se ejecutó y la tabla no existe. Esta migración es idempotente: en bases
-- nuevas creadas desde V1 no hace nada (IF NOT EXISTS).
BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE IF NOT EXISTS horario_academico (
    id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aula BIGINT NOT NULL,
    id_externo VARCHAR(120),
    fecha_inicio TIMESTAMPTZ NOT NULL,
    fecha_fin TIMESTAMPTZ NOT NULL,
    fuente VARCHAR(20) NOT NULL,
    CONSTRAINT horario_aula_fk FOREIGN KEY (id_aula)
        REFERENCES aula (id_aula) ON DELETE RESTRICT,
    CONSTRAINT horario_intervalo_ck CHECK (fecha_fin > fecha_inicio)
);

CREATE UNIQUE INDEX IF NOT EXISTS horario_academico_fuente_externo_uq
    ON horario_academico (fuente, id_externo)
    WHERE id_externo IS NOT NULL;

CREATE INDEX IF NOT EXISTS horario_academico_ocupacion_idx
    ON horario_academico USING gist (
        id_aula,
        tstzrange(fecha_inicio, fecha_fin, '[)')
    );

COMMIT;

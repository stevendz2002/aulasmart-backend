BEGIN;

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    correo VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX usuario_correo_normalizado_uq
    ON usuario (LOWER(correo));

CREATE TABLE rol (
    id_rol SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(30) NOT NULL UNIQUE,
    descripcion VARCHAR(200) NOT NULL
);

CREATE TABLE usuario_rol (
    id_usuario BIGINT NOT NULL,
    id_rol SMALLINT NOT NULL,
    CONSTRAINT usuario_rol_pk PRIMARY KEY (id_usuario, id_rol),
    CONSTRAINT usuario_rol_usuario_fk FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    CONSTRAINT usuario_rol_rol_fk FOREIGN KEY (id_rol)
        REFERENCES rol (id_rol) ON DELETE RESTRICT
);

CREATE TABLE edificio (
    id_edificio BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_siga BIGINT NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL
);

CREATE TABLE tipo_aula (
    id_tipo_aula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_siga BIGINT NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL
);

CREATE TABLE dependencia (
    id_dependencia BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_siga BIGINT NOT NULL UNIQUE,
    nombre VARCHAR(150) NOT NULL
);

CREATE TABLE aula (
    id_aula BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_siga BIGINT NOT NULL UNIQUE,
    nombre VARCHAR(200) NOT NULL,
    id_edificio BIGINT NOT NULL,
    capacidad INTEGER NOT NULL,
    id_tipo_aula BIGINT NOT NULL,
    id_dependencia BIGINT NOT NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT aula_edificio_fk FOREIGN KEY (id_edificio)
        REFERENCES edificio (id_edificio) ON DELETE RESTRICT,
    CONSTRAINT aula_tipo_fk FOREIGN KEY (id_tipo_aula)
        REFERENCES tipo_aula (id_tipo_aula) ON DELETE RESTRICT,
    CONSTRAINT aula_dependencia_fk FOREIGN KEY (id_dependencia)
        REFERENCES dependencia (id_dependencia) ON DELETE RESTRICT,
    CONSTRAINT aula_capacidad_positiva_ck CHECK (capacidad > 0)
);

COMMENT ON COLUMN aula.activa IS
    'Estado local de AulaSmart; el endpoint público consultado no suministra este atributo.';

CREATE INDEX aula_consulta_idx
    ON aula (id_edificio, id_tipo_aula, capacidad)
    WHERE activa;

CREATE TABLE sincronizacion_siga (
    id_sincronizacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurso VARCHAR(20) NOT NULL,
    iniciada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    finalizada_en TIMESTAMPTZ,
    estado VARCHAR(15) NOT NULL,
    registros_procesados INTEGER NOT NULL DEFAULT 0,
    ventana_inicio DATE,
    ventana_fin DATE,
    detalle_error VARCHAR(500),
    CONSTRAINT sincronizacion_recurso_ck
        CHECK (recurso IN ('AULAS', 'EVENTOS')),
    CONSTRAINT sincronizacion_estado_ck
        CHECK (estado IN ('EN_CURSO', 'EXITOSA', 'FALLIDA')),
    CONSTRAINT sincronizacion_registros_ck
        CHECK (registros_procesados >= 0),
    CONSTRAINT sincronizacion_finalizacion_ck CHECK (
        (estado = 'EN_CURSO' AND finalizada_en IS NULL)
        OR (estado IN ('EXITOSA', 'FALLIDA') AND finalizada_en IS NOT NULL)
    ),
    CONSTRAINT sincronizacion_ventana_ck CHECK (
        ventana_inicio IS NULL
        OR ventana_fin IS NULL
        OR ventana_fin >= ventana_inicio
    )
);

CREATE INDEX sincronizacion_ultimo_exito_idx
    ON sincronizacion_siga (recurso, finalizada_en DESC)
    WHERE estado = 'EXITOSA';

CREATE TABLE horario_academico (
    id_horario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_aula BIGINT NOT NULL,
    id_externo VARCHAR(120),
    fecha_inicio TIMESTAMPTZ NOT NULL,
    fecha_fin TIMESTAMPTZ NOT NULL,
    fuente VARCHAR(20) NOT NULL,
    CONSTRAINT horario_aula_fk FOREIGN KEY (id_aula)
        REFERENCES aula (id_aula) ON DELETE RESTRICT,
    CONSTRAINT horario_intervalo_ck CHECK (fecha_fin > fecha_inicio)
);

COMMENT ON COLUMN horario_academico.id_externo IS
    'Nullable hasta confirmar un identificador único en respuestas reales del endpoint de eventos.';

CREATE UNIQUE INDEX horario_academico_fuente_externo_uq
    ON horario_academico (fuente, id_externo)
    WHERE id_externo IS NOT NULL;

CREATE INDEX horario_academico_ocupacion_idx
    ON horario_academico USING gist (
        id_aula,
        tstzrange(fecha_inicio, fecha_fin, '[)')
    );

CREATE TABLE solicitud_aula (
    id_solicitud BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL,
    id_aula BIGINT NOT NULL,
    fecha_inicio TIMESTAMPTZ NOT NULL,
    fecha_fin TIMESTAMPTZ NOT NULL,
    estado VARCHAR(15) NOT NULL DEFAULT 'PENDIENTE',
    motivo VARCHAR(500) NOT NULL,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revisada_por BIGINT,
    revisada_en TIMESTAMPTZ,
    CONSTRAINT solicitud_docente_fk FOREIGN KEY (id_usuario)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT solicitud_aula_fk FOREIGN KEY (id_aula)
        REFERENCES aula (id_aula) ON DELETE RESTRICT,
    CONSTRAINT solicitud_revisor_fk FOREIGN KEY (revisada_por)
        REFERENCES usuario (id_usuario) ON DELETE RESTRICT,
    CONSTRAINT solicitud_intervalo_ck CHECK (fecha_fin > fecha_inicio),
    CONSTRAINT solicitud_estado_ck
        CHECK (estado IN ('PENDIENTE', 'APROBADA', 'RECHAZADA')),
    CONSTRAINT solicitud_motivo_ck CHECK (LENGTH(BTRIM(motivo)) > 0),
    CONSTRAINT solicitud_revision_ck CHECK (
        (estado = 'PENDIENTE' AND revisada_por IS NULL AND revisada_en IS NULL)
        OR
        (estado IN ('APROBADA', 'RECHAZADA')
            AND revisada_por IS NOT NULL
            AND revisada_en IS NOT NULL)
    ),
    CONSTRAINT solicitud_aprobada_sin_solapamiento_ex EXCLUDE USING gist (
        id_aula WITH =,
        tstzrange(fecha_inicio, fecha_fin, '[)') WITH &&
    ) WHERE (estado = 'APROBADA')
);

CREATE INDEX solicitud_aula_usuario_idx
    ON solicitud_aula (id_usuario, creada_en DESC);

CREATE INDEX solicitud_aula_revision_idx
    ON solicitud_aula (estado, creada_en)
    WHERE estado = 'PENDIENTE';

COMMIT;
